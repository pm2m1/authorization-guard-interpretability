"""24 hand-written base scenarios (fictional organisations, people and operations).

Each base scenario supplies everything needed to instantiate ALL three policy families
(existential, universal, cumulative) with the SAME roster, predicate, sources and filler pool,
so that policy family is a within-scenario factor and is not confounded with domain or wording.

Authoring rules (checked by tests/unit/test_scenarios.py):
- no scenario text contains label/condition vocabulary (unknown, missing, insufficient, ...);
- fillers are policy-irrelevant context lines;
- numbers are round and on the declared grid `step`.
"""

